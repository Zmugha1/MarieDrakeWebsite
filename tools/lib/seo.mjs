// Search and AI files: redirects, sitemaps, robots.txt, llms.txt, llms-full.txt, staging headers.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as cheerio from 'cheerio';

const ORIGIN = 'https://thedrakelawfirm.com';
const rel = (u) => (u || '').replace(/^https?:\/\/(www\.)?thedrakelawfirm\.com/i, '') || '/';
const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const text = (html) => cheerio.load(html || '').text().replace(/\s+/g, ' ').trim();

// Old tag and author archives. No page links to them; Google has them from the old sitemap.
const EXTRA_REDIRECTS = [
  ['/author/marie-drake/*', '/colorado/attorneys/marie-drake/'],
  ['/author/*', '/blog/'],
  ['/tag/*', '/blog/'],
];

// Old redirects that point at pages that no longer exist on the live site.
const TARGET_FIXES = {
  '/colorado/attorneys/brandon-richardson/': '/colorado/attorneys/',
  '/blog/should-you-file-for-divorce-before-the-end-of-the-year/': '/blog/should-you-file-for-divorce-before-the-end-of-the-year-in-colorado/',
};

export function writeRedirects(root, site) {
  const data = JSON.parse(readFileSync(join(root, 'inventory', 'redirects.json'), 'utf8'));
  const lines = ['# Generated by tools/build.mjs from inventory/redirects.json. Edit that file, not this one.'];
  const sources = new Set();
  const rules = data.redirects.filter((r) => r.enabled && r.match_type === 'url' && !r.regex);
  const key = (u) => u.split('?')[0].replace(/\/$/, '') || '/';
  const next = new Map(rules.map((r) => [key(r.url), TARGET_FIXES[rel(r.action_data.url)] || rel(r.action_data.url)]));
  // follow chains so every old address goes to its final page in one hop
  const final = (to) => {
    const seen = new Set();
    while (next.has(key(to)) && !seen.has(key(to))) { seen.add(key(to)); to = next.get(key(to)); }
    return to;
  };
  for (const r of rules) {
    const from = r.url.split('?')[0];
    sources.add(key(from));
    lines.push(`${from} ${final(next.get(key(from)))} ${r.action_code}!`);
  }
  lines.push('', '# Tag and author archives');
  for (const [from, to] of EXTRA_REDIRECTS) lines.push(`${from} ${to} 301!`);
  writeFileSync(join(site, '_redirects'), lines.join('\n') + '\n');
  return { count: lines.filter((l) => / \d{3}!$/.test(l)).length, sources };
}

export function writeSitemaps(site, pages, redirectSources) {
  const indexable = pages.filter((p) => {
    if (/\/page\/\d+\/$/.test(p.item.path)) return false; // list pages 2+, not in the old sitemap either
    const robots = p.item.yoast_head_json?.robots || {};
    if (/noindex/.test(robots.index || '')) return false;
    if (/name="robots" content="[^"]*noindex/.test(p.html)) return false;
    return !redirectSources.has(p.item.path.replace(/\/$/, '') || '/');
  });
  const groups = { page: [], post: [], 'video-faqs': [] };
  for (const p of indexable) (groups[p.item.type] || groups.page).push(p);
  const files = [];
  const now = new Date().toISOString();
  for (const [type, list] of Object.entries(groups)) {
    const name = type === 'video-faqs' ? 'video-faqs-sitemap.xml' : `${type}-sitemap.xml`;
    list.sort((a, b) => (a.item.path < b.item.path ? -1 : 1));
    const urls = list.map((p) => {
      const mod = p.item.modified_gmt || p.item.modified || p.item.date;
      const img = p.item.featured_image_url ? `<image:image><image:loc>${xml(p.item.featured_image_url)}</image:loc></image:image>` : '';
      return `<url><loc>${xml(ORIGIN + p.item.path)}</loc>${mod ? `<lastmod>${mod.slice(0, 10)}</lastmod>` : ''}${img}</url>`;
    });
    writeFileSync(join(site, name), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n${urls.join('\n')}\n</urlset>\n`);
    files.push({ name, count: urls.length });
  }
  const index = files.map((f) => `<sitemap><loc>${ORIGIN}/${f.name}</loc><lastmod>${now}</lastmod></sitemap>`).join('\n');
  const body = `<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${index}\n</sitemapindex>\n`;
  // Yoast served the index at /sitemap_index.xml; /sitemap.xml is the common default.
  writeFileSync(join(site, 'sitemap_index.xml'), body);
  writeFileSync(join(site, 'sitemap.xml'), body);
  return files;
}

export function writeRobots(site, production) {
  const body = production
    ? `User-agent: *\nAllow: /\n\nSitemap: ${ORIGIN}/sitemap_index.xml\n`
    : 'User-agent: *\nDisallow: /\n';
  writeFileSync(join(site, 'robots.txt'), body);
}

export function writeHeaders(site, production) {
  const lines = ['/assets/*', '  Cache-Control: public, max-age=31536000, immutable', '/wp-content/uploads/*', '  Cache-Control: public, max-age=31536000'];
  if (!production) lines.unshift('/*', '  X-Robots-Tag: noindex, nofollow');
  writeFileSync(join(site, '_headers'), lines.join('\n') + '\n');
}

// llms.txt: a plain map of the site for AI assistants, built only from the site's own titles and descriptions.
const SECTIONS = [
  ['Family law practice areas', (p) => /^\/(colorado\/(divorce|child-custody|child-support|alimony|property-division|prenup-postnup|paternity|adoption|guardianship)|family-law)\b/.test(p)],
  ['Other practice areas', (p) => /^\/(business-organizations|business-transactions|commercial-civil-litigation|real-estate-law|practice-areas)\//.test(p)],
  ['Attorneys and staff', (p) => /^\/(colorado\/attorneys|stephanie-berardini|tatiana-quijano)\b/.test(p)],
  ['Offices and areas served', (p) => /^\/(colorado\/(locations|areas)|our-location)\b/.test(p)],
  ['City and county pages', (p) => /(arvada|lakewood|golden|boulder|jefferson)/.test(p)],
  ['Resources', (p) => /^\/(faqs|blog|news|video-faqs|contact-us|careers)\/$/.test(p)],
];

export function writeLlms(site, pages) {
  const byPath = new Map(pages.filter((p) => p.item.type === 'page' && !/\/page\/\d+\/$/.test(p.item.path)).map((p) => [p.item.path, p]));
  const home = byPath.get('/');
  const desc = (p) => p.item.yoast_head_json?.description || p.item.yoast_head_json?.og_description || '';
  const title = (p) => text(p.item.title?.rendered || p.item.title || p.item.yoast_head_json?.title || p.item.path);
  const indexable = [...byPath.values()].filter((p) => !/noindex/.test(p.item.yoast_head_json?.robots?.index || '') && !/(privacy-policy|terms-of-use|disclaimer|thank-you|all-forms|\/lp\/)/.test(p.item.path));
  const used = new Set();
  const out = [`# The Drake Law Firm, P.C.`, '', `> ${desc(home) || 'Colorado divorce and family law firm.'}`, '', `Website: ${ORIGIN}/`, `Main phone: (303) 261-8111`, ''];
  for (const [name, test] of SECTIONS) {
    const list = indexable.filter((p) => !used.has(p.item.path) && test(p.item.path)).sort((a, b) => (a.item.path < b.item.path ? -1 : 1));
    if (!list.length) continue;
    out.push(`## ${name}`, '');
    for (const p of list) {
      used.add(p.item.path);
      out.push(`- [${title(p)}](${ORIGIN}${p.item.path})${desc(p) ? ': ' + desc(p) : ''}`);
    }
    out.push('');
  }
  const posts = pages.filter((p) => p.item.type === 'post').sort((a, b) => (a.item.date < b.item.date ? 1 : -1)).slice(0, 20);
  out.push('## Recent articles', '');
  for (const p of posts) out.push(`- [${title(p)}](${ORIGIN}${p.item.path})`);
  out.push('', `More articles: ${ORIGIN}/blog/`, '', '## Optional', '', `- [Full text of the main practice pages](${ORIGIN}/llms-full.txt)`, '');
  writeFileSync(join(site, 'llms.txt'), out.join('\n'));

  // llms-full.txt: the readable text of the practice, attorney and office pages.
  const full = ['# The Drake Law Firm, P.C.: practice, attorney and office pages', '', `Source: ${ORIGIN}/`, ''];
  // Text blocks that repeat on many pages (calls to action, office boxes, review sliders) are kept once.
  const docs = [];
  const freq = new Map();
  for (const p of indexable.filter((x) => used.has(x.item.path)).sort((a, b) => (a.item.path < b.item.path ? -1 : 1))) {
    const $ = cheerio.load(p.html);
    $('header, footer, nav, script, style, form, .pojo-a11y-toolbar, .elementor-location-header, .elementor-location-footer, .elementor-widget-uael-posts, .elementor-widget-testimonial-carousel, .elementor-widget-media-carousel').remove();
    $('p, h1, h2, h3, h4, h5, h6, li, div, section, br, td, th').each((_, el) => { $(el).append('\n'); });
    $('h1, h2, h3, h4').each((_, el) => { $(el).prepend('\n'); });
    const lines = $('main, #main, #content').first().text().replace(/[ \t]+/g, ' ').split(/\s*\n\s*/).map((l) => l.trim()).filter((l) => l.length > 2);
    docs.push([p, lines]);
    for (const l of new Set(lines)) freq.set(l, (freq.get(l) || 0) + 1);
  }
  for (const [p, lines] of docs) {
    const body = lines.filter((l) => freq.get(l) <= 3).join('\n');
    if (!body) continue;
    full.push(`## ${title(p)}`, `URL: ${ORIGIN}${p.item.path}`, '', body, '');
  }
  writeFileSync(join(site, 'llms-full.txt'), full.join('\n'));
}
